// write: lay the word out, then draw every stroke with the brush, twice: the
// second pass a few pixels off register in a second ink, exactly like the
// lettering in the reference films.
function write(c, text, x, y, size, o = {}) {
  const { ink = INKS.navy, ink2 = INKS.plum, align = 'left', tracking = .16, slope = -.02, wobble = 1, seed = 5, offset = 6 } = o;
  const chars = text.split(''), adv = size * (.56 + tracking);
  const total = chars.length * adv - size * tracking;
  let px = align === 'center' ? x - total / 2 : align === 'right' ? x - total : x;
  const strokes = [];
  for (const ch of chars) {
    if (ch !== ' ') for (const s of (LETTERS[ch] || LETTERS.o)) strokes.push(s.map(([u, v]) => [px + (u - slope * (v - .5) * .5) * size, y - size + v * size]));
    px += adv;
  }
  const draw = (col, dx, dy, al) => { c.save(); c.globalAlpha = al; for (const s of strokes) brush(c, plus(s, dx, dy), { w: size * .13, color: col, p: 1, seed: seed + s[0][0] * 7, amp: wobble * size * .02, taper: .8 }); c.restore(); };
  if (ink2) draw(ink2, offset, offset * .6, .8);
  draw(ink, 0, 0, 1);
  return { w: total, h: size };
}
